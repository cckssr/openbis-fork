class PropertyType(
    OpenBisObject, entity="propertyType", single_item_method_name="get_property_type"
):
    """A reusable property type that can be assigned to multiple entity types.

    Property types define the *data type*, label, and other metadata for a
    single property.  They are shared across entity types — one
    ``DESCRIPTION`` property type can be assigned to both ``EXPERIMENTAL_STEP``
    and ``MATERIAL_X``.

    Fetch via ``openbis.get_property_type()`` /
    ``openbis.get_property_types()`` and create new types with
    ``openbis.new_property_type()``.

    Attributes:
        code (str): Unique property type code.
        label (str): Human-readable label shown in forms.
        description (str): Long description of what this property captures.
        dataType (str): One of the values in
            :data:`~pybis.openbis_typing.PropertyDataType`.
        vocabulary (Optional[str]): Vocabulary code for
            ``CONTROLLEDVOCABULARY`` properties.
        schema (Optional[str]): XML schema for ``XML`` properties.

    Example:
        >>> pt = openbis.new_property_type(
        ...     code="CONCENTRATION",
        ...     label="Concentration",
        ...     description="Concentration in µM",
        ...     dataType="REAL",
        ... )
        >>> pt.save()
        >>> sample_type.assign_property(pt, mandatory=False)
    """

    def save(self) -> OpenbisObject:
        """Persist this property type to openBIS (create or update).

        For **new** property types, checks that no type with the same code
        already exists before calling the V3 API.

        Raises:
            ValueError: If a property type with the same code already exists.
        """
        if self.is_new:
            get_single_item = self._get_single_item_method()
            try:
                new_entity_data = get_single_item(self.code)
                raise ValueError(f"propertyType '{self.code}' already exists!")
            except ValueError as e:
                if not "no such propertyType" in str(e):
                    raise e
        super().save()


class PropertyAssignment:
    """A property type assignment linking a :class:`PropertyType` to an entity type.

    :class:`PropertyAssignment` objects are returned by
    :meth:`EntityType.get_property_assignments`.  They record the assignment
    metadata such as the section, ordinal, mandatory flag, and validation
    plugin for a single property within a specific entity type.

    Attributes:
        code (str): Lower-cased property type code.
        dataType (str): Data type of the property.
        section (Optional[str]): Form section heading.
        ordinal (int): Display order within the section.
        mandatory (bool): Whether the property must be filled.
        initialValueForExistingEntities (Any): Default value for existing entities
            when a property is made mandatory retroactively.
        showInEditView (bool): Whether to show in the edit form.
        showRawValueInForms (bool): Whether to show the raw value.
        registrator (str): User who created the assignment.
        registrationDate (str): ISO-8601 creation timestamp.
        plugin (Optional[str]): Name of the validation plugin, if any.
        unique (bool): Whether values must be unique across instances.
        pattern (Optional[str]): Validation pattern string.
        patternType (Optional[str]): Validation pattern type.
    """

    openbis: Any
    data: Optional[dict[str, Any]]

    def __init__(
        self, openbis_obj: Any, data: Optional[dict] = None, **kwargs: Any
    ) -> None:
        """Initialise a PropertyAssignment from a pre-processed data dict.

        Args:
            openbis_obj: The :class:`~pybis.Openbis` connection instance.
            data: Pre-processed assignment dict (code, dataType, etc. already
                extracted from the raw API response).
            **kwargs: Ignored.
        """
        self.openbis = openbis_obj
        self.data = data

    def __getattr__(self, name: str) -> Any:
        if name in self._attrs():
            if name in self.data:
                return self.data[name]
            else:
                return ""

    def __repr__(self) -> str:
        headers = ["attribute", "value"]
        lines = []
        for attr in self._attrs():
            lines.append([attr, nvl(getattr(self, attr, ""))])

        return tabulate(lines, headers=headers)

    def get_property_type(self) -> "PropertyType":
        """Fetch the full :class:`PropertyType` object for this assignment.

        Returns:
            The :class:`PropertyType` corresponding to this assignment's code.

        Example:
            >>> pa = sample_type.get_property_assignments()[0]
            >>> pt = pa.get_property_type()
            >>> print(pt.dataType)
            REAL
        """
        return self.openbis.get_property_type(self.data["propertyType"]["code"])

    def _attrs(self) -> list[str]:
        """Return the list of recognised attribute names.

        Returns:
            A list of attribute name strings.
        """
        return [
            "code",
            "dataType",
            "section",
            "ordinal",
            "mandatory",
            "initialValueForExistingEntities",
            "showInEditView",
            "showRawValueInForms",
            "registrator",
            "registrationDate",
            "plugin",
            "unique",
            "pattern",
            "patternType",
        ]
