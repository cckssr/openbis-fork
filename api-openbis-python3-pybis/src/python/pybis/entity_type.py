"""Entity type and property type classes for openBIS.

Entity types define the *schema* of openBIS entities — which properties
are available, which are mandatory, how they are ordered, and which
validation plugins apply.

Key classes:
    - :class:`EntityType` — base logic shared by all entity types.
    - :class:`SampleType` — type definition for :class:`~pybis.sample.Sample` objects.
    - :class:`DataSetType` — type definition for :class:`~pybis.dataset.DataSet` objects.
    - :class:`ExperimentType` — type definition for :class:`~pybis.experiment.Experiment` objects.
    - :class:`MaterialType` — type definition for (deprecated) :class:`~pybis.material.Material`.
    - :class:`PropertyType` — standalone property type (reusable across entity types).
    - :class:`PropertyAssignment` — a property type assigned to an entity type.
"""

